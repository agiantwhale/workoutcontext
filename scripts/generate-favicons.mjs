// Generates src/generated/favicon-assets.ts from assets/icon.svg so the
// Worker can inline the SVG favicon as a data URL in every page's <head>.
//
// Run before every build/deploy (called from the wrangler build command).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const iconSvg = readFileSync("assets/icon.svg");
const svgDataUrl = `data:image/svg+xml;base64,${iconSvg.toString("base64")}`;

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/favicon-assets.ts",
  `// AUTO-GENERATED by scripts/generate-favicons.mjs. Do not edit; do not commit.
export const FAVICON_SVG_DATA_URL = ${JSON.stringify(svgDataUrl)};
`,
);

console.log("scripts/generate-favicons.mjs: wrote src/generated/favicon-assets.ts");
